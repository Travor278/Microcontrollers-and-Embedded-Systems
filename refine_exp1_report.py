def set_run_font(run, name='仿宋_GB2312', size=11, bold=False):
    run.font.name = name
    run._element.rPr.rFonts.set(qn('w:eastAsia'), name)
    run.font.size = Pt(size)
    run.bold = bold

def replace_para(para, text, font='仿宋_GB2312', size=11, bold=False):
    para.clear()
    run = para.add_run(text)
    set_run_font(run, name=font, size=size, bold=bold)

